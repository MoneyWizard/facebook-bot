// Clean into pure Playwright cookie format
const cleanedCookies = RAW_COOKIES.map(c => {
  const cookie = {
    name: c.name,
    value: c.value,
    domain: c.domain,
    path: c.path || '/',
    httpOnly: Boolean(c.httpOnly),
    secure: Boolean(c.secure),
  };

  // Map expiration
  if (c.expirationDate) {
    cookie.expires = Math.floor(c.expirationDate);
  }

  // Map sameSite strictly to Strict | Lax | None
  if (c.sameSite) {
    const s = String(c.sameSite).toLowerCase();
    if (s === 'lax') cookie.sameSite = 'Lax';
    else if (s === 'strict') cookie.sameSite = 'Strict';
    else if (s === 'none' || s === 'no_restriction') cookie.sameSite = 'None';
  } else {
    // If null and secure is true, None is safe, otherwise Lax
    cookie.sameSite = c.secure ? 'None' : 'Lax';
  }

  return cookie;
});

const outPath = path.resolve('./cookies/tiktok_session.json');
